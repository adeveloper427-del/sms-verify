/**
 * Builds supabase/seed.sql from the demo data in src/data, so the real database
 * starts with the same manufacturers, products, codes and history as the prototype.
 *
 *   npm run seed:generate
 *
 * Times are written relative to now() ("3 days ago"), so the dashboards look fresh
 * whenever the seed is run. Re-running seed.sql resets the demo data.
 */
import { writeFileSync } from 'node:fs';
import { BATCHES } from '../src/data/batches';
import { GENERATED_CODES, GENERATED_VERIFICATIONS } from '../src/data/generated';
import { MANUFACTURERS } from '../src/data/manufacturers';
import { PRODUCTS } from '../src/data/products';
import { REPORTS } from '../src/data/reports';

const NOW = Date.now();

const str = (v: string | null | undefined) => (v === null || v === undefined ? 'null' : `'${v.replace(/'/g, "''")}'`);
const num = (v: number) => String(v);
function ts(iso: string | null) {
  if (!iso) return 'null';
  const secs = Math.round((NOW - new Date(iso).getTime()) / 1000);
  return secs >= 0 ? `now() - interval '${secs} seconds'` : `now() + interval '${-secs} seconds'`;
}
const textArray = (items: string[]) => (items.length ? `array[${items.map(str).join(', ')}]::text[]` : `'{}'::text[]`);

function insert(table: string, columns: string[], rows: string[][], suffix = '', chunk = 200) {
  const out: string[] = [];
  for (let i = 0; i < rows.length; i += chunk) {
    const values = rows.slice(i, i + chunk).map((r) => `  (${r.join(', ')})`).join(',\n');
    out.push(`insert into ${table} (${columns.join(', ')}) values\n${values}${suffix ? `\n${suffix}` : ''};`);
  }
  return out.join('\n\n');
}

const sql = `-- =====================================================================
-- Halisi Verify — demo data (generated by scripts/generate-seed.ts, do not edit by hand)
-- Run AFTER schema.sql. Running it again resets the demo data.
-- All companies and data are fictional.
-- =====================================================================

begin;

delete from verifications;
delete from reports;
delete from verification_codes;
delete from batches;
delete from products;

${insert(
  'manufacturers',
  ['id', 'name', 'registration_no', 'contact_person', 'email', 'phone', 'county', 'address', 'industry', 'status', 'joined_at'],
  MANUFACTURERS.map((m) => [
    str(m.id), str(m.name), str(m.registrationNo), str(m.contactPerson), str(m.email), str(m.phone),
    str(m.county), str(m.address), str(m.industry), str(m.status), ts(m.joinedAt),
  ]),
  `on conflict (id) do update set
  name = excluded.name, registration_no = excluded.registration_no, contact_person = excluded.contact_person,
  email = excluded.email, phone = excluded.phone, county = excluded.county, address = excluded.address,
  industry = excluded.industry, status = excluded.status, joined_at = excluded.joined_at`,
)}

${insert(
  'products',
  ['id', 'manufacturer_id', 'name', 'category', 'description', 'sku', 'status', 'created_at'],
  PRODUCTS.map((p) => [str(p.id), str(p.manufacturerId), str(p.name), str(p.category), str(p.description), str(p.sku), str(p.status), ts(p.createdAt)]),
)}

${insert(
  'batches',
  ['id', 'product_id', 'manufacturer_id', 'batch_number', 'quantity', 'manufacturing_date', 'expiry_date', 'codes_generated', 'code_status', 'code_first', 'code_last', 'status', 'created_at'],
  BATCHES.map((b) => [
    str(b.id), str(b.productId), str(b.manufacturerId), str(b.batchNumber), num(b.quantity), ts(b.manufacturingDate),
    ts(b.expiryDate), num(b.codesGenerated), str(b.codeStatus), str(b.codeRange?.first), str(b.codeRange?.last), str(b.status), ts(b.createdAt),
  ]),
)}

${insert(
  'verification_codes',
  ['code', 'batch_id', 'product_id', 'manufacturer_id', 'status', 'review_status', 'verification_count', 'created_at', 'last_verified_at'],
  GENERATED_CODES.map((c) => [
    str(c.code), str(c.batchId), str(c.productId), str(c.manufacturerId), str(c.status), str(c.reviewStatus),
    num(c.verificationCount), ts(c.createdAt), ts(c.lastVerifiedAt),
  ]),
)}

${insert(
  'verifications',
  ['code', 'product_id', 'batch_id', 'manufacturer_id', 'phone', 'location', 'created_at', 'result', 'count_at_time', 'channel'],
  [...GENERATED_VERIFICATIONS].reverse().map((v) => [
    str(v.code), str(v.productId), str(v.batchId), str(v.manufacturerId), str(v.phone), str(v.location),
    ts(v.timestamp), str(v.result), num(v.countAtTime), str(v.channel),
  ]),
)}

${insert(
  'reports',
  ['id', 'reference', 'code', 'product_id', 'product_name', 'manufacturer_id', 'reason', 'description', 'location', 'reporter_phone', 'created_at', 'status', 'notes'],
  REPORTS.map((r) => [
    str(r.id), str(r.reference), str(r.code), str(r.productId), str(r.productName), str(r.manufacturerId), str(r.reason),
    str(r.description), str(r.location), str(r.reporterPhone), ts(r.createdAt), str(r.status), textArray(r.notes),
  ]),
)}

alter sequence report_ref_seq restart with 2641;

update settings set
  suspicious_threshold = 3, high_risk_threshold = 20, sms_shortcode = '22384', verify_keyword = 'VERIFY',
  report_keyword = 'REPORT', auto_flag_suspicious = true, notify_manufacturers = true, email_alerts = false,
  data_retention_days = 365
where id = 1;

commit;
`;

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(
  `seed.sql written: ${MANUFACTURERS.length} manufacturers, ${PRODUCTS.length} products, ${BATCHES.length} batches, ` +
    `${GENERATED_CODES.length} codes, ${GENERATED_VERIFICATIONS.length} verifications, ${REPORTS.length} reports`,
);
